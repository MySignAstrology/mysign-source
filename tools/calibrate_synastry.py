"""
Regenerate the reference distribution behind the compatibility score.

A raw synastry total mostly measures "two charts exist" — every pair throws
about forty contacts, so the absolute number says almost nothing. What matters
is where a pair sits against ordinary pairs, so the score is a z-score against
this reference, not a raw sum.

Run after touching any weight in engine/synastry.py, then paste the printed
REFERENCE block back into it. Sample is deterministic.

    python tools/calibrate_synastry.py [pairs]
"""
import random
import statistics
import sys

from engine import synastry as S
from engine.chart import natal

CITIES = [(41.88, -87.63), (40.71, -74.01), (34.05, -118.24),
          (51.51, -0.13), (19.43, -99.13), (-33.87, 151.21)]


def main(n=500):
    rng = random.Random(20260823)
    charts = []
    for _ in range(int(n ** 0.5) + 12):
        lat, lon = rng.choice(CITIES)
        charts.append(natal(rng.randint(1988, 2006), rng.randint(1, 12),
                            rng.randint(1, 28), rng.random() * 24, lat, lon))
    out = {}
    # Every case score() can be asked for. One known time is one case either
    # way round (overlays count in both directions). "none" is two date-only
    # charts — the case that used to borrow "partial"'s reference and scored
    # about fourteen points low as a result.
    for label, aa, ab in (("full", True, True), ("partial", True, False),
                          ("none", False, False)):
        acc = {"spark": [], "ease": [], "staying": []}
        for _ in range(n):
            a, b = rng.sample(charts, 2)
            raw, _, _ = S.raw_dims(a, b, aa, ab)
            for k in acc: acc[k].append(raw[k])
        out[label] = {k: (round(statistics.fmean(v), 4), round(statistics.pstdev(v), 4))
                      for k, v in acc.items()}
    print(f"# regenerated by tools/calibrate_synastry.py, {n} random pairs per config")
    print("REFERENCE = {")
    for label, dims in out.items():
        inner = ", ".join(f'"{k}": ({m}, {s})' for k, (m, s) in dims.items())
        print(f'    "{label}": {{{inner}}},')
    print("}")
    return out


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 500)
